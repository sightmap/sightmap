// Command gen syncs the browser runtime embedded into the Go generator from
// its canonical source at the repository root: webmcp/src/runtime/runtime.js
// is copied to go/webmcp/runtime.js, and the generator version is read from
// webmcp/package.json into go/webmcp/version_gen.go. Run via
// `go generate ./webmcp/...` from go/; CI fails on drift, mirroring the
// go/skills embed pattern.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
)

func main() {
	// Working directory is go/webmcp (go:generate runs in the package dir).
	repoRoot := filepath.Join("..", "..")
	src := filepath.Join(repoRoot, "webmcp", "src", "runtime", "runtime.js")
	data, err := os.ReadFile(src)
	if err != nil {
		fatal(err)
	}
	if err := os.WriteFile("runtime.js", data, 0o644); err != nil {
		fatal(err)
	}

	pkgData, err := os.ReadFile(filepath.Join(repoRoot, "webmcp", "package.json"))
	if err != nil {
		fatal(err)
	}
	var pkg struct {
		Version string `json:"version"`
	}
	if err := json.Unmarshal(pkgData, &pkg); err != nil {
		fatal(err)
	}
	versionGo := fmt.Sprintf(`// Code generated by go generate ./webmcp/...; DO NOT EDIT.
// Source: <repo>/webmcp/package.json.

package webmcp

// GeneratorVersion is the @sightmap/webmcp-codegen version this generator
// mirrors; it appears verbatim in every bundle's provenance banner, so the Go
// and Node generators stay byte-identical.
const GeneratorVersion = %q
`, pkg.Version)
	if err := os.WriteFile("version_gen.go", []byte(versionGo), 0o644); err != nil {
		fatal(err)
	}
	fmt.Fprintf(os.Stderr, "gen-webmcp: synced runtime.js (%d bytes) + version %s\n", len(data), pkg.Version)
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "gen-webmcp:", err)
	os.Exit(1)
}
