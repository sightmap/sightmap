// Command gen syncs the browser runtime embedded into the Go generator from
// its canonical source at the repository root: webmcp/src/runtime/runtime.js
// is copied to go/webmcp/runtime.js, the generator version is read from
// webmcp/package.json into go/webmcp/version_gen.go, and the fixture IR used
// by the jsdom runtime tests is regenerated. Run via
// `go generate ./webmcp/...` from go/; CI fails on drift.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/sightmap/sightmap/go/webmcp"
)

func main() {
	// Working directory is go/webmcp (go:generate runs in the package dir).
	repoRoot := filepath.Join("..", "..")
	src := filepath.Join(repoRoot, "webmcp", "src", "runtime", "runtime.js")
	data, err := os.ReadFile(src)
	if err != nil {
		fatal(err)
	}
	if err := os.WriteFile("runtime.js", data, 0o644); err != nil {
		fatal(err)
	}

	pkgData, err := os.ReadFile(filepath.Join(repoRoot, "webmcp", "package.json"))
	if err != nil {
		fatal(err)
	}
	var pkg struct {
		Version string `json:"version"`
	}
	if err := json.Unmarshal(pkgData, &pkg); err != nil {
		fatal(err)
	}
	if pkg.Version == "" {
		fatal(fmt.Errorf("webmcp/package.json has no version"))
	}
	versionGo := fmt.Sprintf(`// Code generated by go generate ./webmcp/...; DO NOT EDIT.
// Source: <repo>/webmcp/package.json.

package webmcp

// GeneratorVersion appears in every bundle's provenance banner.
const GeneratorVersion = %q
`, pkg.Version)
	if err := os.WriteFile("version_gen.go", []byte(versionGo), 0o644); err != nil {
		fatal(err)
	}

	irPath, n, err := dumpFixtureIR(repoRoot)
	if err != nil {
		fatal(err)
	}
	fmt.Fprintf(os.Stderr, "gen-webmcp: synced runtime.js (%d bytes) + version %s + %s (%d bytes)\n",
		len(data), pkg.Version, irPath, n)
}

func dumpFixtureIR(repoRoot string) (string, int, error) {
	fixture := filepath.Join(repoRoot, "webmcp", "test", "fixtures", "site")
	toolsFile := filepath.Join(fixture, "webmcp.tools.yaml")
	manifest, errs, _, err := webmcp.LoadManifest(toolsFile)
	if err != nil {
		return "", 0, err
	}
	if len(errs) > 0 {
		return "", 0, fmt.Errorf("fixture manifest: %s", strings.Join(errs, "; "))
	}
	corpus, err := webmcp.LoadCorpus(filepath.Join(fixture, ".sightmap"))
	if err != nil {
		return "", 0, err
	}
	ir, cerrs, _ := webmcp.Compile(corpus, manifest)
	if len(cerrs) > 0 {
		return "", 0, fmt.Errorf("fixture compile: %s", strings.Join(cerrs, "; "))
	}
	out := webmcp.StringifyJSON(ir) + "\n"
	path := filepath.Join(fixture, "ir.json")
	if err := os.WriteFile(path, []byte(out), 0o644); err != nil {
		return "", 0, err
	}
	return path, len(out), nil
}

func fatal(err error) {
	fmt.Fprintln(os.Stderr, "gen-webmcp:", err)
	os.Exit(1)
}
